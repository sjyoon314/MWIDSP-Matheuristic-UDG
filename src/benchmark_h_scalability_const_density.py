"""
Benchmark Script for Section 6.3: Constant-Density Scaling.

This script evaluates the scalability frontier by comparing the optimal 
configurations of two matheuristic architectures:
1. Grid Ensemble (using the 'node_only' scoring metric)
2. Clique Ensemble (using the 'edge_aware_min' scoring metric)

It executes the algorithms via subprocesses, aggregates the results, 
and generates log-log plots comparing time complexity and objective costs 
across Edge-Heavy (EG), Neutral (NG), and Node-Heavy (VG) environments.
"""

import os
import sys
import glob
import subprocess
from datetime import datetime
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# =============================================================================
# [1] HARDCODED CONFIGURATION
# =============================================================================
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

IN_DIR = os.path.join(SCRIPT_DIR, '..', 'instances', 'udg_constant_density')
OUT_DIR = os.path.join(SCRIPT_DIR, '..', 'results', 'complexity_const_density')
EXP_NAME = "const_density"

TARGET_SCALES = [500, 1000, 2000, 5000]

# (Algorithm Type, Script File, Scoring Metric)
OPTIMAL_MATCHUPS = [
    ("grid", "heuristic_grid_ensemble.py", "node_only"),
    ("clique", "heuristic_clique_ensemble.py", "edge_aware_min")
]
# =============================================================================

def estimate_empirical_complexity(n_array, time_array):
    t_safe = np.maximum(time_array, 1e-5)
    log_n = np.log(n_array)
    log_t = np.log(t_safe)
    slope, _ = np.polyfit(log_n, log_t, 1)
    return slope

def get_environment_type(instance_name):
    if "nw1000_ew10" in instance_name:
        return "VG (Node-Heavy)"
    elif "nw10_ew1000" in instance_name:
        return "EG (Edge-Heavy)"
    else:
        return "NG (Neutral)"

def get_expected_csv_name(n_str, algo_type, score_type, exp_name):
    """
    Reconstructs the EXACT filename generated by the internal heuristic scripts.
    """
    if score_type == 'node_only':
        base_name = f"{algo_type}_heuristic"
    else:
        base_name = f"{algo_type}_heuristic_{score_type}"
    return f"{n_str}_{base_name}_{exp_name}_results.csv"

def run_benchmark():
    os.makedirs(OUT_DIR, exist_ok=True)
    
    print(f"[{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}] Starting Scalability Benchmark")
    print(f"Input Directory : {IN_DIR}")
    print(f"Output Directory: {OUT_DIR}\n")
    
    # ==========================================
    # Phase 1: Execute Algorithms
    # ==========================================
    for n in TARGET_SCALES:
        print(f"{'-'*40}\nEvaluating Scale: N={n}\n{'-'*40}")
        
        # [FIX]: Use strict string of N (e.g. "500") to avoid double underscore issues.
        n_str = str(n)
        instance_pattern = os.path.join(IN_DIR, f"{n_str}_*.rgg")
        all_instances = glob.glob(instance_pattern)
        expected_count = len(all_instances)
        
        if expected_count == 0:
            print(f"  [WARNING] No instances found for N={n}. Skipping.")
            continue
            
        print(f"  Found {expected_count} instances. Starting execution...")

        for algo_type, script_file, score in OPTIMAL_MATCHUPS:
            out_csv = get_expected_csv_name(n_str, algo_type, score, EXP_NAME)
            out_path = os.path.join(OUT_DIR, out_csv)
            
            is_done = False
            if os.path.exists(out_path):
                with open(out_path, 'r') as f:
                    lines = [l for l in f.readlines()[1:] if l.strip()]
                    if len(lines) >= expected_count:
                        is_done = True
            
            if is_done:
                print(f"  [SKIP] {algo_type} ({score}) already processed. Found: {out_csv}")
            else:
                print(f"  [RUN] Executing {algo_type} ({score})...")
                
                script_path = os.path.join(SCRIPT_DIR, script_file)
                if not os.path.exists(script_path):
                    print(f"  [ERROR] Script not found: {script_path}")
                    continue
                    
                cmd = [
                    sys.executable, script_path, 
                    "-i", IN_DIR, 
                    "-s", n_str,  # Pass "500" instead of "500_"
                    "-o", OUT_DIR, 
                    "-e", EXP_NAME, 
                    "--score_type", score
                ]
                
                try: 
                    # Let the internal print statements show on the console
                    subprocess.run(cmd, check=True)
                except subprocess.CalledProcessError as e: 
                    print(f"  [ERROR] Execution failed for {algo_type}: {e}")

    # ==========================================
    # Phase 2: Data Aggregation
    # ==========================================
    print("\nAggregating results and calculating empirical complexity...")
    results = []
    
    for n in TARGET_SCALES:
        n_str = str(n)
        
        for algo_type, _, score in OPTIMAL_MATCHUPS:
            csv_name = get_expected_csv_name(n_str, algo_type, score, EXP_NAME)
            csv_path = os.path.join(OUT_DIR, csv_name)
            
            if os.path.exists(csv_path):
                df = pd.read_csv(csv_path, skipinitialspace=True)
                if not df.empty:
                    df['Environment'] = df['instance'].apply(get_environment_type)
                    
                    display_name = "Grid Ensemble" if algo_type == "grid" else "Clique Ensemble"
                    
                    for env, group in df.groupby('Environment'):
                        results.append({
                            'N': n, 
                            'Algorithm': display_name, 
                            'Score': score,
                            'Environment': env,
                            'Time': group['time'].mean(), 
                            'Cost': group['cost'].mean()
                        })
            else:
                print(f"  [WARNING] Missing result file: {csv_name}")

    if not results:
        print("\n[ERROR] No data collected. Aborting visualization.")
        return

    df_res = pd.DataFrame(results)
    
    summary_csv = os.path.join(OUT_DIR, 'constant_density_summary.csv')
    df_res.to_csv(summary_csv, index=False)
    print(f"Summary saved: {summary_csv}")

    # ==========================================
    # Phase 3: Visualization
    # ==========================================
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(18, 7))
    fig.suptitle('Scalability Frontier (Constant-Density): Optimal Grid vs. Optimal Clique', 
                 fontsize=16, fontweight='bold', y=0.95)
    
    color_map = {'EG (Edge-Heavy)': '#d62728', 'NG (Neutral)': '#2ca02c', 'VG (Node-Heavy)': '#1f77b4'}
    ls_map = {'Grid Ensemble': '-', 'Clique Ensemble': '--'}
    marker_map = {'Grid Ensemble': 'o', 'Clique Ensemble': '^'}

    for (algo, env), group in df_res.groupby(['Algorithm', 'Environment']):
        group = group.sort_values('N')
        n_vals = group['N'].values
        time_vals = group['Time'].values
        cost_vals = group['Cost'].values
        
        k_power = estimate_empirical_complexity(n_vals, time_vals)
        
        label_time = f"{algo} [{env}] O(N^{k_power:.2f})"
        label_cost = f"{algo} [{env}]"
        
        c = color_map[env]
        ls = ls_map[algo]
        m = marker_map[algo]
        lw = 2.5
        
        ax1.plot(n_vals, time_vals, marker=m, linestyle=ls, color=c, label=label_time, linewidth=lw, markersize=8)
        ax2.plot(n_vals, cost_vals, marker=m, linestyle=ls, color=c, label=label_cost, linewidth=lw, markersize=8)

    ax1.set_xscale('log')
    ax1.set_yscale('log')
    ax1.set_xlabel('Number of Nodes (N) [Log Scale]', fontsize=12)
    ax1.set_ylabel('Execution Time (s) [Log Scale]', fontsize=12)
    ax1.set_title('Empirical Time Complexity', fontsize=14)
    ax1.set_xticks(TARGET_SCALES)
    ax1.set_xticklabels([str(n) for n in TARGET_SCALES])
    ax1.grid(True, which="both", ls="--", alpha=0.5)
    ax1.legend(fontsize=10, loc='upper left')

    ax2.set_xlabel('Number of Nodes (N)', fontsize=12)
    ax2.set_ylabel('Average Cost', fontsize=12)
    ax2.set_title('Cost Scaling Progression', fontsize=14)
    ax2.set_xticks(TARGET_SCALES)
    ax2.grid(True, ls="--", alpha=0.7)
    ax2.legend(fontsize=10, loc='upper left')

    plt.tight_layout(rect=[0, 0, 1, 0.93])
    plot_path = os.path.join(OUT_DIR, 'constant_density_comparison.png')
    plt.savefig(plot_path, dpi=300, bbox_inches='tight')
    print(f"Plot saved successfully: {plot_path}")
    print("\nBenchmark completed successfully.")

if __name__ == "__main__":
    run_benchmark()